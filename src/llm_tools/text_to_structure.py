    # 测试查询
    queries = [
        "Design a copper-based MOF with paddle-wheel clusters for CO2 capture",
        "I need a water-stable Zr-MOF with high surface area",
        "Generate a MOF with open metal sites for selective gas separation"
    ]

    for query in queries:
        print(f"\nQuery: \"{query}\"")
        print("-" * 70)

        result = generator.generate_from_text(
            query,
            method="hybrid",
            top_k=3,
            verbose=True
        )

        # 验证top候选
        top_candidate = result["candidates"][0]
        is_valid, issues = StructureValidator.validate_structure(top_candidate)

        print(f"Top candidate validation: {'✓ Valid' if is_valid else '✗ Invalid'}")
        if issues:
            print(f"Issues: {', '.join(issues)}")
        print()


